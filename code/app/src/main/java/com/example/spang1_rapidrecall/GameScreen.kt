import kotlin.random.Random
import kotlin.time.Duration.Companion.milliseconds

@Composable
fun GameScreenDisplay(
    //seq length which needed to generate random seq now, and then navigating to home,
    sequenceLength: Int,
    onNavigateToHome: () -> Unit = {},
    onAttemptSubmitted: (AttemptRecord) -> Unit = {}    //following code generated by GoogleGemini when prompted "How do I store records so I can pass them to the LogScreen later?" 2026/10/02
    //essentially it contains all the key info for the logs, and required so the parent component can actually log the result into the logs
) {
    val sequence = remember(sequenceLength) { List(sequenceLength) { Random.nextInt(0, 10) } }
    var currentDigit by remember { mutableStateOf<Int?>(null) }
    var isSequenceFinished by remember { mutableStateOf(false) }
    var userGuessInput by remember { mutableStateOf("") }
    var userGuessResult by remember { mutableStateOf<String?>(null) }
    var submittedGuess by remember { mutableStateOf("") }
    var inputTimeStamp by remember { mutableStateOf<Long?>(null) }

    LaunchedEffect(sequence) { // LaunchedEffect to start the sequence where the numbers show up and then dissapear
        //https://developer.android.com/develop/ui/compose/side-effects
        delay(500L.milliseconds) //  pause before sequence starts
        for (digit in sequence) {
            currentDigit = digit
            delay(1000L.milliseconds) // display num for 1 second
            currentDigit = null
            delay(200L.milliseconds) // brief pause so they dont mush together
        }
        isSequenceFinished = true //signal the sequence finish so we can show the input box for the user to enter their attempt
    }

    Surface(
        modifier = Modifier.fillMaxSize()
    ) {
        Box(modifier = Modifier.fillMaxSize().padding(16.dp)) {
            Button(
                onClick = onNavigateToHome,
                modifier = Modifier.align(Alignment.TopStart)
            ) {
                Text("Home")
            }
        }
        //the meat and potatoes (main logic where numbers show up and stuff)
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center
        ) {
            if (!isSequenceFinished) {
                Text(
                    text = "Memorize the Sequence",
                    fontWeight = FontWeight.Bold
                )

                Spacer(modifier = Modifier.height(16.dp))
                //lil card so the number can show up somewhere
                Card(
                    modifier = Modifier.size(72.dp),
                    colors = CardDefaults.cardColors(
                        containerColor = Color(0xFFFFA6C9)
                    )
                ) {
                    Box(
                        modifier = Modifier.fillMaxSize(),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = currentDigit?.toString() ?: "",  //convert the digit into a string so i can display it in ,well, text
                            fontWeight = FontWeight.Bold,
                            color = Color.White,
                            textAlign = TextAlign.Center
                        )
                    }
                }
            } else {    //user answer time
                Text(
                    text = "What was the sequence?",
                    fontWeight = FontWeight.Bold,
                    color = Color(0xFFFFA6C9)
                )

                Spacer(modifier = Modifier.height(16.dp))

                when (userGuessResult) {    //if the user is guessing, show the input field, otherwise hide it because i had a bug where i could keep guessing even though i had already seen the answer and thats not good
                    null -> {
                        Row( //use row to hold input field and button
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(8.dp)
                        ) { // input field
                            OutlinedTextField(
                                value = userGuessInput,
                                onValueChange = { userGuessInput = it },
                                label = { Text("Guess") },
                                modifier = Modifier.width(160.dp)
                            )

                            Button(
                                onClick = {
                                    val targetSequenceStr = sequence.joinToString("")   //since we were printing the digits our separely, we gotta put them together now
                                    //The following syntax to get the time is from Google Gemini, "How do I get the current timestamp", 2026/10/02
                                    val now = System.currentTimeMillis()
                                    inputTimeStamp = now
                                    //--
                                    submittedGuess = userGuessInput.trim()  //clean up the users guess/attempt for more accurate comparisons in case user error
                                    val isCorrect = (submittedGuess == targetSequenceStr)   //save whether or not users answer is correct
                                    userGuessResult = if (isCorrect) "CORRECT" else "INCORRECT"

                                    val record = AttemptRecord( //saving the record for the logs
                                        sequenceLength = sequenceLength,
                                        userGuess = submittedGuess,
                                        targetSequence = targetSequenceStr,
                                        isCorrect = isCorrect,
                                        timestamp = now
                                    )
                                    onAttemptSubmitted(record)
                                }
                            ) {
                                Text("Submit")
                            }
                        }
                    }
                    "CORRECT" -> { //if correct just show its correct
                        Text(
                            text = "CORRECT",
                            fontWeight = FontWeight.Bold,
                            color = Color.Green
                        )
                    }
                    "INCORRECT" -> { //if it was incorrect then show the users guess compared to the actual sequence
                        Text(
                            text = "INCORRECT",
                            fontWeight = FontWeight.Bold,
                            color = Color.Red
                        )
                        Spacer(modifier = Modifier.height(8.dp))
                        Text(
                            text = "correct: ${sequence.joinToString("")}"
                        )
                        Spacer(modifier = Modifier.height(4.dp))
                        Text(
                            text = "your guess: $submittedGuess"
                        )
                    }
                }
            }
        }
    }
}

